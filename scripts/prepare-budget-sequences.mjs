/**
 * Prepare the homepage's smaller scroll assets from the existing WebP sequences.
 * Original frames remain untouched. Run: node scripts/prepare-budget-sequences.mjs
 */
import { mkdir, readdir, readFile, rm, writeFile } from "node:fs/promises";
import { createHash } from "node:crypto";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import sharp from "sharp";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const frameCount = 24;
const frameWidth = 600;
const columns = 2;
const rows = 3;
const framesPerAtlas = columns * rows;
const quality = 58;
const manifest = {};
const obsolete = [];
let totalBytes = 0;

for (const id of [3, 6, 5]) {
  const sourceDirectory = join(root, "public/frames", String(id));
  const sourceFrames = (await readdir(sourceDirectory))
    .map((name) => new RegExp(`^${id}\\.(\\d+)\\.webp$`).exec(name))
    .filter(Boolean).map((match) => Number(match[1])).sort((a, b) => a - b);
  if (sourceFrames.length < frameCount || sourceFrames.some((frame, index) => frame !== index + 1)) {
    throw new Error(`Sequence ${id} must contain contiguous source frames starting at 1.`);
  }
  const sourceFrameIndices = Array.from({ length: frameCount }, (_, index) =>
    1 + Math.round(index * (sourceFrames.length - 1) / (frameCount - 1)));
  const destination = join(root, "public/atlases", String(id));
  await mkdir(destination, { recursive: true });
  const atlasPaths = [];
  let frameHeight;
  let encodedBytes = 0;

  for (let first = 0; first < frameCount; first += framesPerAtlas) {
    const tiles = [];
    for (const sourceFrame of sourceFrameIndices.slice(first, first + framesPerAtlas)) {
      // PNG is an intermediate buffer only, avoiding a second lossy WebP encode.
      const { data, info } = await sharp(await readFile(join(sourceDirectory, `${id}.${sourceFrame}.webp`)))
        .resize({ width: frameWidth }).png({ compressionLevel: 0 }).toBuffer({ resolveWithObject: true });
      frameHeight ??= info.height;
      if (info.height !== frameHeight) throw new Error(`Sequence ${id} has inconsistent frame dimensions.`);
      tiles.push(data);
    }
    const atlas = await sharp({ create: {
      width: frameWidth * columns, height: frameHeight * rows, channels: 3, background: "#111318",
    } }).composite(tiles.map((input, index) => ({
      input, left: index % columns * frameWidth, top: Math.floor(index / columns) * frameHeight,
    }))).webp({ quality, effort: 6 }).toBuffer();
    const digest = createHash("sha256").update(atlas).digest("hex").slice(0, 8);
    const name = `${id}.${first / framesPerAtlas + 1}.${digest}.webp`;
    await writeFile(join(destination, name), atlas);
    atlasPaths.push(`/atlases/${id}/${name}`);
    encodedBytes += atlas.length;
  }
  manifest[id] = {
    frameCount, frameWidth, frameHeight, columns, rows, atlasPaths,
    sourceFrameCount: sourceFrames.length, sourceFrameIndices, encodedBytes,
  };
  const current = new Set(atlasPaths.map((url) => url.split("/").at(-1)));
  for (const name of await readdir(destination)) {
    if (new RegExp(`^${id}\\.\\d+\\.[a-f0-9]{8}\\.webp$`).test(name) && !current.has(name)) {
      obsolete.push(join(destination, name));
    }
  }
  totalBytes += encodedBytes;
}

const generatedDirectory = join(root, "src/lib/generated");
await mkdir(generatedDirectory, { recursive: true });
await writeFile(join(generatedDirectory, "budgetSequences.ts"),
  "// Generated by scripts/prepare-budget-sequences.mjs. Do not edit manually.\n" +
  "export const generatedBudgetSequences = " + JSON.stringify(manifest, null, 2) + " as const;\n");
// Remove only superseded files with this generator's hashed naming convention.
await Promise.all(obsolete.map((file) => rm(file)));
const atlasRequests = Object.values(manifest).reduce((count, sequence) => count + sequence.atlasPaths.length, 0);
console.log(JSON.stringify({ sequences: Object.keys(manifest), frameCount, atlasRequests, totalBytes }, null, 2));
